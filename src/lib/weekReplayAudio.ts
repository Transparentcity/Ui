/**
 * Week Replay — synthesized audio engine (no external assets).
 *
 * The sound is meant to be read, not just heard. It follows the brand's own
 * terms: calm, specific, no hype. So it behaves like an instrument the map is
 * playing rather than a soundtrack laid over it —
 *
 * - x on the map is stereo position, y is register, so a dot in the north-west
 *   sounds high and to the left;
 * - pitch comes from the event's category, taken from its position in the
 *   shared color palette, so a category always sounds like itself and the
 *   most common ones sit lowest;
 * - an ambient pad tracks the same night and weekend signals the map washes
 *   itself with, and breathes on the 4-second cycle of the bracket loader;
 * - key moments ring as soft bells, and the week closes on a slow exhale.
 *
 * Three choices do most of the work in keeping it listenable. Voices are soft
 * mallets with long reverberant tails instead of bare sine pips, so overlapping
 * events blur into one texture. Onsets are rate limited, so a busy Tuesday
 * reads as weight and density rather than a burst of clicks. And everything
 * sits in a pentatonic scale, so no ordering of events can produce a dissonance.
 *
 * buildAudioSchedule() is pure and testable without a browser.
 * createReplayAudioEngine() drives a live AudioContext with a rolling
 * lookahead. renderReplayAudio() renders the same schedule offline for the
 * video export, so a shared clip sounds identical to what was on screen.
 */

import {
  SUBCATEGORY_PALETTE,
  nightness,
  weekendness,
  type PlaybackTimeline,
} from "./weekReplay";

// ── Public types ────────────────────────────────────────────────────────────

export interface ReplayAudioEvent {
  /** Playback ms at which the event lands. */
  playMs: number;
  /** Horizontal position as a 0 (west) … 1 (east) fraction of the map. */
  panX: number;
  /** Vertical position as a 0 (north) … 1 (south) fraction of the map. */
  posY: number;
  /** The event's category color, from the shared subcategory palette. */
  color: string;
}

export interface AudioTick {
  /** Playback ms at which this note sounds. */
  playMs: number;
  /** Stereo pan, –1 (left) … +1 (right). */
  panX: number;
  /** Fundamental: the category's seat in the chord currently sounding. */
  freqHz: number;
  /** Relative velocity 0–1; rises with how many events merged into this note. */
  level: number;
  /** Which instrument plays it — one per category. */
  timbre: number;
}

export interface AudioChime {
  playMs: number;
  /** Gold-ring / 311 photo events ring brighter. */
  isPhoto: boolean;
  /** Root of the chord sounding when it fires, so it lands in the harmony. */
  rootHz: number;
}


export interface AudioPadPoint {
  playMs: number;
  nightLevel: number;
  weekendLevel: number;
}

export interface AudioSchedule {
  ticks: AudioTick[];
  chimes: AudioChime[];
  /** Playback duration in ms; the closing swell starts here. */
  endMs: number;
  /** Sampled at PAD_INTERVAL_MS so the pad can be ramped continuously. */
  padPoints: AudioPadPoint[];
}

export interface ReplayAudioEngine {
  /** Begin playback from a position — call in response to a play gesture. */
  start(atPlayMs?: number): void;
  pause(): void;
  seek(playMs: number): void;
  setMuted(muted: boolean): void;
  dispose(): void;
}

// ── Musical material ────────────────────────────────────────────────────────

/** F3. Everything is measured in semitones from here. */
const ROOT_HZ = 174.61;
/** Pad root, an octave below the melodic root. */
const PAD_ROOT_HZ = ROOT_HZ / 2; // F2

const semitones = (n: number) => Math.pow(2, n / 12);

/**
 * The week's chord progression, all drawn from F Dorian.
 *
 * This is what makes the replay read as music rather than as a scale being
 * plucked at: the harmony moves underneath while events arrive in whatever
 * order the week happened. A category holds a fixed seat in each chord, so it
 * keeps its identity but changes pitch as the chords turn — the melody is
 * generated by the data crossing a moving harmony, not composed.
 *
 * Every voice is a degree of one mode, so no chord can clash with the pad and
 * no two events can clash with each other, whatever order they land in.
 */
interface Chord {
  /** Semitones above the root for the pad's bass. */
  bass: number;
  /** One seat per category, ascending. */
  voices: readonly number[];
}

const PROGRESSION: readonly Chord[] = [
  { bass: 0, voices: [0, 3, 7, 10, 14] }, // i     F Ab C Eb G
  { bass: 3, voices: [3, 7, 10, 12, 14] }, // III  Ab C Eb F G
  { bass: 5, voices: [5, 7, 9, 12, 14] }, // IV    Bb C D F G
  { bass: 10, voices: [0, 5, 9, 10, 14] }, // VII  F Bb D Eb G
];

/** Chord changes per replay: the progression turns twice over the week. */
const CHORD_SEGMENTS = PROGRESSION.length * 2;

/** Which chord is sounding at a playback position. */
function chordIndexAt(playMs: number, durationMs: number): number {
  if (!(durationMs > 0)) return 0;
  const segment = Math.floor((playMs / durationMs) * CHORD_SEGMENTS);
  return Math.max(0, Math.min(CHORD_SEGMENTS - 1, segment)) % PROGRESSION.length;
}

/**
 * A category's index in the shared palette, which upstream assigns by
 * descending event count — so index 0 is the busiest category of the week.
 */
function categoryIndex(color: string): number {
  const found = SUBCATEGORY_PALETTE.indexOf(color);
  return found >= 0 ? found : 0;
}

/**
 * Pitch for an event: its category takes a seat in the chord that is currently
 * sounding, and how far north it sits on the map picks the octave.
 */
function eventFreq(color: string, posY: number, chord: Chord): number {
  const index = categoryIndex(color);
  const voice = chord.voices[index % chord.voices.length];
  // Only the map lifts the register. Categories past the fifth seat used to
  // climb an octave to stay distinct, which is no longer needed now that each
  // one has its own instrument — and it kept the top of the range shrill.
  const northLift = posY < 0.45 ? 1 : 0;
  return ROOT_HZ * semitones(voice) * Math.pow(2, northLift);
}

